import { test, expect } from '@playwright/test'

const editor = (page: any, id: string) => page.locator(`#segment-align-${id} [data-segment-target="true"]`)
const action = (page: any, name: string) => page.locator('.workbench-ribbon__top-actions').getByRole('button', { name, exact: true })
const writes = (page: any) => page.evaluate(() => (window as any).alignmentHarness.requests.filter((r: any) => r.url.endsWith('/replace-range')))

test('中部拆分保留焦点，连续点击和快捷键只提交一次，撤回重做无重复', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/e2e/alignment-harness.html')
  await editor(page, 'pair-40').click()
  await page.evaluate(() => (window as any).alignmentHarness.setDelay(300))
  await action(page, '拆分').click()
  await page.keyboard.press('Alt+s')
  await expect(editor(page, 'new-1')).toBeFocused()
  await expect(editor(page, 'new-1')).toHaveText('Target 40 A')
  await expect(editor(page, 'new-2')).toHaveText('Target 40 B')
  expect(await writes(page)).toHaveLength(1)
  await action(page, '撤回').click()
  await expect(editor(page, 'new-3')).toBeFocused()
  await expect(editor(page, 'new-3')).toHaveText('Target 40 A\nTarget 40 B')
  await action(page, '前进').click()
  await expect(editor(page, 'new-4')).toBeFocused()
  await expect(editor(page, 'new-5')).toHaveText('Target 40 B')
  expect(errors).toEqual([])
})

