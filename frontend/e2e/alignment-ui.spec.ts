test('跨页撤回加载结果所在页，不回到第一页的开头', async ({ page }) => {
  await page.goto('/e2e/alignment-harness.html')
  await editor(page, 'pair-99').click()
  await action(page, '拆分').click()
  await expect(editor(page, 'new-1')).toBeFocused()
  await page.evaluate(() => (window as any).alignmentHarness.store.loadSegmentPage({ page: 2 }))
  await expect(editor(page, 'new-2')).toBeVisible()
  await action(page, '撤回').click()
  await expect(editor(page, 'new-3')).toBeFocused()
  await expect(editor(page, 'new-3')).toHaveText('Target 99 A\nTarget 99 B')
  expect(await page.evaluate(() => (window as any).alignmentHarness.store.currentPage)).toBe(1)
})

test('合并和边界移动保持操作行，撤回恢复两侧内容', async ({ page }) => {
  await page.goto('/e2e/alignment-harness.html')
  await editor(page, 'pair-40').click({ modifiers: ['Control'] })
  await editor(page, 'pair-41').click({ modifiers: ['Control'] })
  await action(page, '合并').click()
  await expect(editor(page, 'new-1')).toBeFocused()
  await expect(editor(page, 'new-1')).toHaveText('Target 40 A\nTarget 40 B\nTarget 41 A\nTarget 41 B')
  await action(page, '撤回').click()
  await expect(editor(page, 'new-2')).toBeFocused()
  await action(page, '下移').click()
  await expect(editor(page, 'new-4')).toBeFocused()
  await expect(editor(page, 'new-4')).toHaveText('Target 40 A')
  await expect(editor(page, 'new-5')).toHaveText('Target 40 B\nTarget 41 A\nTarget 41 B')
  await action(page, '撤回').click()
  await expect(editor(page, 'new-6')).toBeFocused()
  await expect(editor(page, 'new-6')).toHaveText('Target 40 A\nTarget 40 B')
})

test('虚拟列表中拆分屏幕外活动行会渲染并聚焦结果', async ({ page }) => {
  await page.goto('/e2e/alignment-harness.html?virtual')
  await expect(editor(page, 'pair-0')).toBeVisible()
  await page.evaluate(() => (window as any).alignmentHarness.store.setActiveSentence('align-pair-40'))
  await page.keyboard.press('Alt+s')
  await expect(editor(page, 'new-1')).toBeFocused()
  await expect(editor(page, 'new-1')).toBeVisible()
  expect(await writes(page)).toHaveLength(1)
})

test('提交成功但读取失败时重试只读取，不再拆分', async ({ page }) => {
  await page.goto('/e2e/alignment-harness.html')
  await editor(page, 'pair-40').click()
  await page.evaluate(() => (window as any).alignmentHarness.setFailRefresh(true))
  await action(page, '拆分').click()
  await expect(page.getByTestId('alignment-retry-refresh')).toBeVisible()
  await expect(action(page, '拆分')).toBeDisabled()
  await page.evaluate(() => (window as any).alignmentHarness.setFailRefresh(false))
  await page.getByTestId('alignment-retry-refresh').click()
  await expect(editor(page, 'new-1')).toBeFocused()
  expect(await writes(page)).toHaveLength(1)
  await expect(action(page, '撤回')).toBeEnabled()
})

test('人工编辑先保存，无法无损拆开时保留文本且不记录历史', async ({ page }) => {
  await page.goto('/e2e/alignment-harness.html')
  await editor(page, 'pair-40').fill('人工修改，不明确句段边界')
  await action(page, '拆分').click()
  await expect(action(page, '拆分')).toBeEnabled()
  await expect(editor(page, 'pair-40')).toHaveText('人工修改，不明确句段边界')
  await expect(action(page, '撤回')).toBeDisabled()
  const requests = await page.evaluate(() => (window as any).alignmentHarness.requests)
  const save = requests.findIndex((r: any) => r.url === '/alignment-pairs/pair-40/text')
  const split = requests.findIndex((r: any) => r.url.endsWith('/replace-range'))
  expect(save).toBeGreaterThan(-1)
  expect(split).toBeGreaterThan(save)
})

test('保存失败不发结构请求；配对冲突保留列表和撤回历史', async ({ page }) => {
  await page.goto('/e2e/alignment-harness.html')
  await page.evaluate(() => (window as any).alignmentHarness.setFailSave(true))
  await editor(page, 'pair-40').fill('保存失败的文本')
  await action(page, '拆分').click()
  await expect(action(page, '拆分')).toBeEnabled()
  expect(await writes(page)).toHaveLength(0)
  await expect(editor(page, 'pair-40')).toHaveText('保存失败的文本')
  await page.reload()
  await editor(page, 'pair-40').click()
  await action(page, '拆分').click()
  await expect(editor(page, 'new-1')).toBeFocused()
  await page.evaluate(() => (window as any).alignmentHarness.setFailReplace(true))
  await action(page, '撤回').click()
  await expect(action(page, '撤回')).toBeEnabled()
  await expect(editor(page, 'new-1')).toHaveText('Target 40 A')
  await expect(action(page, '前进')).toBeDisabled()
})
